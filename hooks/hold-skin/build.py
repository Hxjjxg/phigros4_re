"""Build the standalone Frida 16 hold sprite hook; does not access a device."""
from pathlib import Path
import subprocess
import json
import struct


def verify_native_profile(binary, profile):
    """Check the five guarded instruction windows against a local original ELF."""
    with Path(binary).open('rb') as stream:
        header = stream.read(64)
        if header[:6] != b'\x7fELF\x02\x01' or struct.unpack_from('<H', header, 18)[0] != 183:
            raise ValueError('Expected an AArch64 little-endian ELF64 binary')
        phoff = struct.unpack_from('<Q', header, 32)[0]
        phsize, phnum = struct.unpack_from('<HH', header, 54)
        loads = []
        for index in range(phnum):
            stream.seek(phoff + index * phsize)
            kind, flags, offset, vaddr, paddr, size, memsize, align = struct.unpack('<IIQQQQQQ', stream.read(56))
            if kind == 1:
                loads.append((vaddr, offset, size))
        base = int(profile['createNoteRva'], 0)
        sites = [{'name':'entry', 'offset':0, 'signature':profile['entrySignature']}] + profile['sites']
        for site in sites:
            address = base + site['offset']
            expected = bytes.fromhex(site['signature'])
            for vaddr, offset, size in loads:
                if vaddr <= address and address + len(expected) <= vaddr + size:
                    stream.seek(offset + address - vaddr)
                    actual = stream.read(len(expected))
                    break
            else:
                raise ValueError('Native profile address is not mapped: ' + site['name'])
            if actual != expected:
                raise ValueError('Native profile fingerprint mismatch: ' + site['name'])
            if site['name'] == 'entry':
                word = struct.unpack_from('<I', actual)[0]
                immediate = (word >> 15) & 0x7f
                if immediate >= 64:
                    immediate -= 128
                if -immediate * 8 != profile['stackFrameSize']:
                    raise ValueError('Native profile stack frame does not match the guarded prologue')


def main():
    root = Path(__file__).resolve().parent
    source = '// Generated by hooks/hold-skin/build.py; edit src/ and rebuild.\n'
    profile = json.loads((root / 'native-profile.json').read_text(encoding='utf-8'))
    binary = root.parents[1] / 'work' / 'il2cpp' / 'libil2cpp_arm64.so'
    if binary.exists():
        verify_native_profile(binary, profile)
    source += 'globalThis.PhiHoldProfile = ' + json.dumps(profile, separators=(',', ':')) + ';\n'
    source += '\n'.join((root / 'src' / name).read_text(encoding='utf-8')
                        for name in ['core.js', 'runtime.js', 'skin.js'])
    output = root / 'phigros_hold_skin.js'
    output.write_text(source, encoding='utf-8')
    subprocess.run(['node', '--check', str(output)], check=True)
    print(output)


if __name__ == '__main__':
    main()
